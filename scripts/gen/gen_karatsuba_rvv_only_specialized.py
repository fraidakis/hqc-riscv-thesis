#!/usr/bin/env python3
"""Generate fixed-size RVV-only Karatsuba functions for HQC sizes 277/561/901.

Split rule per AP-2 request:
  n0 = ceil(n/2), n1 = floor(n/2)
Stop recursion at n <= 16.

Recomposition uses RVV helpers:
  - rvv_copy_u64
  - rvv_xor3_u64
"""

from __future__ import annotations

from pathlib import Path

ROOT_NS = [277, 561, 901]
THRESHOLD = 16

REPO_ROOT = Path(__file__).resolve().parents[2]
OUT_HEADER = (
    REPO_ROOT
    / "src/poly_mul/vector/rvv_only/karatsuba_rvv/karatsuba_rvv_specialized_gen.h"
)


def split_sizes(n: int) -> tuple[int, int]:
    return (n + 1) // 2, n // 2


def collect_sizes(n: int, out: set[int]) -> None:
    if n <= THRESHOLD:
        return
    if n in out:
        return
    out.add(n)
    n0, n1 = split_sizes(n)
    collect_sizes(n0, out)
    collect_sizes(n1, out)


def child_call(dst: str, xa: str, xb: str, n: int) -> str:
    if n <= THRESHOLD:
        if n == 8:
            return f"clmul_leaf_n8({dst}, {xa}, {xb});"
        return f"clmul_leaf({dst}, {xa}, {xb}, {n}u);"
    return f"kmul_{n}({dst}, {xa}, {xb}, child_buf);"


def emit_function(n: int) -> str:
    n0, n1 = split_sizes(n)
    two_n0 = 2 * n0
    two_n1 = 2 * n1

    lines: list[str] = []
    lines.append(f"static void kmul_{n}(uint64_t * __restrict__ r,")
    lines.append("                    const uint64_t * __restrict__ a,")
    lines.append("                    const uint64_t * __restrict__ b,")
    lines.append("                    uint64_t * __restrict__ tmp)")
    lines.append("{")
    lines.append("    uint64_t *z0        = tmp;")
    lines.append(f"    uint64_t *z2        = z0 + {two_n0}u;")
    lines.append(f"    uint64_t *zmid      = z2 + {two_n1}u;")
    lines.append(f"    uint64_t *ta        = zmid + {two_n0}u;")
    lines.append(f"    uint64_t *tb        = ta + {n0}u;")
    lines.append(f"    uint64_t *child_buf = tb + {n0}u;")
    lines.append("")
    lines.append(f"    {child_call('z0', 'a', 'b', n0)}")
    lines.append(f"    {child_call('z2', f'a + {n0}u', f'b + {n0}u', n1)}")
    lines.append("")
    lines.append(f"    for (size_t i = 0; i < {n0}u; i++) {{")
    lines.append(f"        ta[i] = a[i] ^ (i < {n1}u ? a[{n0}u + i] : 0u);")
    lines.append(f"        tb[i] = b[i] ^ (i < {n1}u ? b[{n0}u + i] : 0u);")
    lines.append("    }")
    lines.append("")
    lines.append(f"    {child_call('zmid', 'ta', 'tb', n0)}")
    lines.append("")
    lines.append("    /* Loop 1: r[0..2*n0-1] = z0 */")
    lines.append(f"    rvv_copy_u64(r, z0, {two_n0}u);")
    lines.append("")
    lines.append("    /* Loop 2: r[2*n0..2*n0+2*n1-1] = z2 */")
    lines.append(f"    rvv_copy_u64(r + {two_n0}u, z2, {two_n1}u);")
    lines.append("")
    lines.append("    /* Loop 3A: r[n0+i] ^= zmid[i] ^ z0[i] ^ z2[i], i in [0, 2*n1) */")
    lines.append(f"    rvv_xor3_u64(r + {n0}u, zmid, z0, z2, {two_n1}u);")

    if two_n0 > two_n1:
        rem = two_n0 - two_n1
        rm_off = n0 + two_n1
        lines.append("")
        lines.append("    /* Loop 3B: odd-n tail where z2 is absent (at most one word) */")
        lines.append(
            f"    rvv_xor3_u64(r + {rm_off}u, zmid + {two_n1}u, z0 + {two_n1}u, (const uint64_t *)0, {rem}u);"
        )

    lines.append("}")
    lines.append("")
    return "\n".join(lines)


def generate_header() -> str:
    sizes: set[int] = set()
    for root in ROOT_NS:
        collect_sizes(root, sizes)
    ordered = sorted(sizes)

    out: list[str] = []
    out.append("#ifndef HQC_KARATSUBA_RVV_SPECIALIZED_GEN_H")
    out.append("#define HQC_KARATSUBA_RVV_SPECIALIZED_GEN_H")
    out.append("")
    out.append("#include <stddef.h>")
    out.append("#include <stdint.h>")
    out.append("")
    out.append("/* Auto-generated by scripts/gen/gen_karatsuba_rvv_only_specialized.py. */")
    out.append("/* Fixed-size recursion roots: 277, 561, 901. */")
    out.append("")

    for n in ordered:
        out.append(emit_function(n))

    out.append("#endif")
    out.append("")
    return "\n".join(out)


def main() -> None:
    OUT_HEADER.parent.mkdir(parents=True, exist_ok=True)
    OUT_HEADER.write_text(generate_header())
    print(f"Generated {OUT_HEADER}")


if __name__ == "__main__":
    main()
