#!/usr/bin/env python3
"""
tests/kat/gen_kat_seeds.py

One-time script: parse the official HQC KAT .rsp file and emit a C header
containing the 100 entropy seeds and 100 expected shared-secret values.

Usage:
    python3 gen_kat_seeds.py --rsp vendor/hqc-ref/KAT/hqc-<LVL>/PQCkemKAT_<N>.rsp \
                             --level <128|192|256>                                    \
                             --out tests/kat/generated/kat_seeds_<LVL>.h

The .rsp format (NIST PQC submission):
    count = N
    seed = <48-byte hex>
    pk = <hex>
    sk = <hex>
    ct = <hex>
    ss = <64-byte hex>
    (blank line between vectors)

Output header provides:
    kat_seeds[100][48]  — entropy inputs for randombytes_init()
    kat_ss[100][64]     — expected ss values for comparison / documentation
"""

import argparse
import sys
import os
import re


def parse_rsp(path: str):
    """Return list of dicts with 'seed' and 'ss' as bytes objects."""
    vectors = []
    current = {}
    with open(path, "r") as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith("#"):
                if current:
                    vectors.append(current)
                    current = {}
                continue
            m = re.match(r"^(\w+)\s*=\s*([0-9a-fA-F]+)$", line)
            if m:
                key, val = m.group(1), m.group(2)
                if key in ("seed", "ss"):
                    current[key] = bytes.fromhex(val)
    if current:
        vectors.append(current)
    return vectors


def bytes_to_c_array_row(data: bytes) -> str:
    """Format bytes as comma-separated 0xHH values on one line."""
    return ", ".join(f"0x{b:02x}" for b in data)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--rsp",   required=True, help="Path to .rsp file")
    ap.add_argument("--level", required=True, choices=["128", "192", "256"])
    ap.add_argument("--out",   required=True, help="Output .h path")
    args = ap.parse_args()

    vectors = parse_rsp(args.rsp)
    if len(vectors) != 100:
        print(f"ERROR: expected 100 vectors, got {len(vectors)}", file=sys.stderr)
        sys.exit(1)

    for i, v in enumerate(vectors):
        if len(v.get("seed", b"")) != 48:
            print(f"ERROR: vector {i} seed length {len(v.get('seed', b''))}, expected 48",
                  file=sys.stderr)
            sys.exit(1)
        if len(v.get("ss", b"")) != 64:
            print(f"ERROR: vector {i} ss length {len(v.get('ss', b''))}, expected 64",
                  file=sys.stderr)
            sys.exit(1)

    os.makedirs(os.path.dirname(args.out), exist_ok=True)

    guard = f"HQC_KAT_SEEDS_{args.level}_H"
    with open(args.out, "w") as out:
        out.write(f"/* tests/kat/generated/kat_seeds_{args.level}.h\n")
        out.write(f" *\n")
        out.write(f" * AUTO-GENERATED by gen_kat_seeds.py — DO NOT EDIT.\n")
        out.write(f" * Source: {args.rsp}\n")
        out.write(f" */\n\n")
        out.write(f"#ifndef {guard}\n")
        out.write(f"#define {guard}\n\n")
        out.write(f"#include <stdint.h>\n\n")

        out.write(f"/* Entropy seeds for randombytes_init() — 100 × 48 bytes */\n")
        out.write(f"static const uint8_t kat_seeds[100][48] = {{\n")
        for v in vectors:
            out.write(f"    {{ {bytes_to_c_array_row(v['seed'])} }},\n")
        out.write(f"}};\n\n")

        out.write(f"/* Expected shared secrets — 100 × 64 bytes */\n")
        out.write(f"static const uint8_t kat_ss[100][64] = {{\n")
        for v in vectors:
            out.write(f"    {{ {bytes_to_c_array_row(v['ss'])} }},\n")
        out.write(f"}};\n\n")

        out.write(f"#endif /* {guard} */\n")

    print(f"Wrote {args.out} ({len(vectors)} vectors)")


if __name__ == "__main__":
    main()
